import Foundation

/// The inputs the company scores are computed from. Field names match
/// `StockMetricsInput` in `apps/web/src/lib/evaluation/types.ts` so the same
/// JSON drives both implementations in the parity test.
public struct StockMetrics: Codable, Equatable, Sendable {
    public var price: Double?
    public var revenueYoy: Double?
    public var grossMargin: Double?
    public var operatingMargin: Double?
    public var roe: Double?
    public var fcfMargin: Double?
    public var fcfConversion: Double?
    public var netDebt: Double?
    public var debtToEquity: Double?
    public var currentRatio: Double?
    public var peRatio: Double?
    public var pegRatio: Double?
    public var evEbitda: Double?
    public var fcfYield: Double?
    public var perf3m: Double?
    public var perf12m: Double?
    public var ma50: Double?
    public var ma200: Double?
    public var rsVsSector: Double?

    public init() {}
}

public enum ScoreStatus: String, Sendable {
    case strong, neutral, weak
}

/// The three questions the company page answers, each scored 0–100.
///
/// A line-for-line port of `apps/web/src/lib/evaluation/scoring.ts`. The web
/// computes these in the browser, so there is no endpoint to call; until the
/// scoring moves to the backend, the two copies must agree. They are held
/// together by `StockScoringParityTests`, which replays cases generated by the
/// TypeScript implementation (`scripts/gen_scoring_golden.mjs`). Change the
/// thresholds in one place only by changing them in both and regenerating.
public enum StockScoring {
    // JS `Math.round` rounds halves up; Swift's default rounds them to even.
    private static func clamp(_ v: Double) -> Int {
        Int(max(0, min(100, (v + 0.5).rounded(.down))))
    }

    // MARK: Health

    private static func revenueGrowth(_ v: Double?) -> Double {
        guard let v else { return 50 }
        if v > 0.20 { return 95 }
        if v > 0.10 { return 80 }
        if v > 0.05 { return 65 }
        if v > 0.00 { return 50 }
        if v > -0.05 { return 30 }
        return 10
    }

    private static func margin(_ gross: Double?, _ operating: Double?) -> Double {
        var s = 0.0, w = 0.0
        if let gross { s += gross > 0.5 ? 90 : gross > 0.35 ? 70 : gross > 0.2 ? 50 : 25; w += 1 }
        if let operating { s += operating > 0.2 ? 90 : operating > 0.1 ? 70 : operating > 0 ? 45 : 15; w += 1 }
        return w > 0 ? s / w : 50
    }

    private static func freeCashFlow(_ margin: Double?, _ conversion: Double?) -> Double {
        var s = 0.0, w = 0.0
        if let margin { s += margin > 0.25 ? 95 : margin > 0.15 ? 80 : margin > 0.05 ? 60 : margin > 0 ? 40 : 15; w += 1 }
        if let conversion { s += conversion > 1.0 ? 95 : conversion > 0.8 ? 80 : conversion > 0.5 ? 55 : 25; w += 1 }
        return w > 0 ? s / w : 50
    }

    private static func returnOnEquity(_ roe: Double?) -> Double {
        guard let roe else { return 50 }
        // ROE above 100% is inflated by buybacks; cap it for scoring.
        let r = min(abs(roe), 0.5)
        if r > 0.30 { return 90 }
        if r > 0.20 { return 75 }
        if r > 0.10 { return 60 }
        if r > 0.00 { return 40 }
        return 20
    }

    private static func balanceSheet(_ netDebt: Double?, _ currentRatio: Double?, _ debtToEquity: Double?) -> Double {
        var s = 0.0, w = 0.0
        if let netDebt {
            if netDebt < 0 {
                s += 95  // net cash
            } else {
                s += netDebt < 5e9 ? 75 : netDebt < 20e9 ? 60 : netDebt < 50e9 ? 45 : 30
            }
            w += 1
        }
        if let currentRatio {
            s += currentRatio > 2 ? 90 : currentRatio > 1.5 ? 75 : currentRatio > 1 ? 55 : currentRatio > 0.75 ? 35 : 15
            w += 1
        }
        if let debtToEquity {
            s += debtToEquity < 0.3 ? 90 : debtToEquity < 0.75 ? 70 : debtToEquity < 1.5 ? 50 : debtToEquity < 3 ? 30 : 10
            w += 1
        }
        return w > 0 ? s / w : 50
    }

    public static func health(_ m: StockMetrics) -> Int {
        let s1 = revenueGrowth(m.revenueYoy) * 0.20
        let s2 = margin(m.grossMargin, m.operatingMargin) * 0.20
        let s3 = freeCashFlow(m.fcfMargin, m.fcfConversion) * 0.20
        let s4 = returnOnEquity(m.roe) * 0.20
        let s5 = balanceSheet(m.netDebt, m.currentRatio, m.debtToEquity) * 0.20
        return clamp(s1 + s2 + s3 + s4 + s5)
    }

    // MARK: Valuation

    private static func fcfYield(_ v: Double?) -> Double {
        guard let v else { return 50 }
        if v > 0.08 { return 95 }
        if v > 0.05 { return 80 }
        if v > 0.03 { return 60 }
        if v > 0.01 { return 40 }
        return 20
    }

    private static func evEbitda(_ v: Double?) -> Double {
        guard let v else { return 50 }
        if v < 8 { return 90 }
        if v < 12 { return 75 }
        if v < 18 { return 55 }
        if v < 25 { return 38 }
        if v < 35 { return 25 }
        return 12
    }

    private static func priceToEarnings(_ v: Double?) -> Double {
        guard let v else { return 50 }
        if v < 12 { return 90 }
        if v < 18 { return 75 }
        if v < 25 { return 58 }
        if v < 35 { return 40 }
        if v < 50 { return 25 }
        return 10
    }

    private static func peg(_ v: Double?) -> Double {
        guard let v else { return 50 }
        if v < 0.8 { return 90 }
        if v < 1.2 { return 75 }
        if v < 2.0 { return 55 }
        if v < 3.0 { return 35 }
        return 15
    }

    public static func valuation(_ m: StockMetrics) -> Int {
        let s1 = fcfYield(m.fcfYield) * 0.28
        let s2 = evEbitda(m.evEbitda) * 0.27
        let s3 = priceToEarnings(m.peRatio) * 0.22
        let s4 = peg(m.pegRatio) * 0.17
        let s5 = 50 * 0.06  // DCF placeholder: neutral
        return clamp(s1 + s2 + s3 + s4 + s5)
    }

    // MARK: Trend

    private static func momentum(_ perf3m: Double?, _ perf12m: Double?) -> Double {
        var s = 0.0, w = 0.0
        if let perf3m {
            s += perf3m > 0.15 ? 90 : perf3m > 0.05 ? 72 : perf3m > 0 ? 55 : perf3m > -0.1 ? 38 : 18
            w += 1.5  // three months weighs more than twelve
            s = s * 1.5
        }
        if let perf12m {
            s += perf12m > 0.25 ? 88 : perf12m > 0.10 ? 70 : perf12m > 0 ? 52 : perf12m > -0.2 ? 33 : 14
            w += 1
        }
        return w > 0 ? s / w : 50
    }

    private static func movingAverages(_ price: Double?, _ ma50: Double?, _ ma200: Double?) -> Double {
        guard let price else { return 50 }
        var s = 0.0, w = 0.0
        if let ma50 {
            let pct = price / ma50 - 1
            s += pct > 0.05 ? 80 : pct > 0 ? 62 : pct > -0.05 ? 42 : 22
            w += 1
        }
        if let ma200 {
            let pct = price / ma200 - 1
            s += pct > 0.10 ? 85 : pct > 0 ? 65 : pct > -0.10 ? 38 : 18
            w += 1
        }
        return w > 0 ? s / w : 50
    }

    private static func relativeStrength(_ rs3m: Double?) -> Double {
        guard let rs3m else { return 50 }
        if rs3m > 0.10 { return 88 }
        if rs3m > 0.03 { return 72 }
        if rs3m > -0.03 { return 52 }
        if rs3m > -0.10 { return 34 }
        return 16
    }

    public static func trend(_ m: StockMetrics) -> Int {
        let hasAnyTrend = m.perf3m != nil || m.perf12m != nil || m.ma50 != nil || m.ma200 != nil
        guard hasAnyTrend else { return 50 }
        let s1 = momentum(m.perf3m, m.perf12m) * 0.35
        let s2 = movingAverages(m.price, m.ma50, m.ma200) * 0.30
        let s3 = relativeStrength(m.rsVsSector) * 0.20
        let s4 = 50 * 0.15  // volume + EPS revision: neutral placeholder
        return clamp(s1 + s2 + s3 + s4)
    }

    // MARK: Overall

    public static func overall(health: Int, valuation: Int, trend: Int) -> Int {
        clamp(Double(health) * 0.40 + Double(valuation) * 0.30 + Double(trend) * 0.30)
    }

    public static func label(forOverall score: Int) -> String {
        if score >= 80 { return "Attractive" }
        if score >= 60 { return "Moderately Positive" }
        if score >= 40 { return "Neutral" }
        if score >= 20 { return "Caution" }
        return "High Risk / Avoid"
    }

    public static func status(_ score: Int) -> ScoreStatus {
        if score >= 65 { return .strong }
        if score >= 42 { return .neutral }
        return .weak
    }
}
